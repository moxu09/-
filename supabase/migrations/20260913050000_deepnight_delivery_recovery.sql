  perform public.deepnight_enqueue_delivery_recovery(
    p_guild_id, 'extension_financial_effects', p_extension_id::text,
    jsonb_build_object('extension_id', p_extension_id, 'payment_method', '月結')
  );
  return jsonb_build_object(
    'already_processed', false, 'extension', to_jsonb(v_extension),
    'amount', v_amount, 'cashback', v_cashback,
    'used_amount', coalesce(v_account.used_amount, 0),
    'monthly_limit', coalesce(v_account.monthly_limit, 0),
    'available_amount', greatest(0,
      coalesce(v_account.monthly_limit, 0) - coalesce(v_account.used_amount, 0))
  );
