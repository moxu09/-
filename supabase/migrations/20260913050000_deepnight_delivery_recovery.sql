      guild_id, customer_id, customer_name, customer_username,
      assigned_player, discord_id, staff_name, order_type, order_item,
      game, service, service_name, note, channel_id, source_channel_id,
      price, final_price, order_amount, staff_salary, bonus_amount,
      salary_rate, salary_level, platform_income, platform_expense,
      paid, paid_at, payment_method, salary_paid, status, completed_at,
      accepted_at, order_finished_at, is_deleted
    ) values (
      p_guild_id, p_tipper_id, '<@' || p_tipper_id || '>',
      '<@' || p_tipper_id || '>', v_staff_id, v_staff_id, v_staff_name,
      '打賞', v_item, '打賞', '打賞：' || v_item, '打賞：' || v_item,
      '打賞｜' || p_operation_key || ':' || v_index::text,
      p_channel_id, p_channel_id, v_amount, v_amount, v_amount,
      round(v_amount * (v_rate / 100.0)), 0, v_rate,
      nullif(v_allocation->>'salary_level', ''), v_amount,
      round(v_amount * (v_rate / 100.0)), true, now(), p_payment_method,
      false, 'completed', now(), now(), now(), false
    ) returning * into v_order;
    v_orders := v_orders || jsonb_build_array(to_jsonb(v_order));
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'order_financial_effects', v_order.id::text,
      jsonb_build_object('order_id', v_order.id,
        'payment_method', p_payment_method, 'amount', v_amount)
