    or v_order.customer_id is distinct from p_customer_id
  then raise exception '加時付款人與原訂單不一致'; end if;
  if not coalesce(v_extension.paid, false) then
    raise exception '加時尚未付款，不能套用';
  end if;
  if coalesce(v_extension.amount, 0) <= 0 then raise exception '加時金額錯誤'; end if;

  if not coalesce(v_extension.applied_to_salary, false) then
    v_old_price := coalesce(v_order.final_price, v_order.price, 0);
    v_new_price := v_old_price + v_extension.amount;
    v_old_service := coalesce(v_order.service, v_order.order_item, '陪玩訂單');
    v_note := trim(coalesce(v_order.note, '') || E'\n[加時] ' ||
      coalesce(v_extension.extension_text, '加時') || '｜+NT$' || v_extension.amount::text);
    update public.play_orders
    set final_price = v_new_price, price = v_new_price,
        service = v_old_service || '｜加時：' || coalesce(v_extension.extension_text, '加時'),
        note = v_note, updated_at = now()
    where id = v_order.id and guild_id = p_guild_id
    returning * into v_order;
    update public.order_extensions
    set applied_to_salary = true, applied_at = now(), updated_at = now()
    where id = p_extension_id and guild_id = p_guild_id
    returning * into v_extension;
    v_applied := true;
  else
    v_old_price := greatest(0,
      coalesce(v_order.final_price, v_order.price, 0) - v_extension.amount);
    v_new_price := coalesce(v_order.final_price, v_order.price, 0);
  end if;

  return jsonb_build_object(
    'applied', v_applied,
    'already_processed', not v_applied,
    'old_price', v_old_price,
    'new_price', v_new_price,
    'extension', to_jsonb(v_extension),
    'order', to_jsonb(v_order)
  );
end;
$function$;

-- Manual bank/QR/crypto confirmations use the same paid boundary as automatic
-- payments: paid + coupon consumption + both durable downstream jobs commit in
-- one transaction.  Re-clicking an already-paid order only repairs the jobs;
-- it never applies payment or coupon consumption twice.
create or replace function public.deepnight_confirm_manual_payment(
  p_order_ids uuid[],
  p_guild_id text,
  p_confirmed_by text,
  p_delivery_type text default 'order_dispatch'
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_order public.play_orders%rowtype;
  v_customer_id text;
  v_count integer := 0;
  v_orders jsonb;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  if coalesce(cardinality(p_order_ids), 0) = 0 then
    raise exception '訂單資料不可為空';
  end if;
  if coalesce(p_confirmed_by, '') = '' then
    raise exception '找不到確認付款的客服';
  end if;
  if p_delivery_type not in ('order_dispatch', 'customer_confirmation') then
    raise exception '付款後續流程錯誤';
  end if;

  for v_order in
    select * from public.play_orders
    where id = any(p_order_ids)
      and guild_id = p_guild_id
    order by id
    for update
  loop
    v_count := v_count + 1;
    v_customer_id := coalesce(v_customer_id, v_order.customer_id);
    if v_order.customer_id is distinct from v_customer_id then
      raise exception '同批確認付款不可包含不同客人';
    end if;
    if coalesce(v_order.is_deleted, false)
      or v_order.status in ('cancelled', 'refunded', 'completed')
    then
      raise exception '訂單已取消、退款或結束，不能確認付款';
    end if;
    if not coalesce(v_order.paid, false)
      and (v_order.status is null
        or v_order.status not in ('waiting_payment', 'quoted', 'waiting_confirm'))
    then
      raise exception '訂單目前不能確認付款';
    end if;
  end loop;
  if v_count <> cardinality(p_order_ids) then
    raise exception '部分深夜訂單不存在，未確認付款';
  end if;

  update public.play_orders
  set paid = true,
      paid_at = coalesce(paid_at, now()),
      status = case
        when p_delivery_type = 'customer_confirmation' then 'waiting_confirm'
        else 'pending'
      end,
      quote_status = case
        when p_delivery_type = 'order_dispatch' then 'dispatched'
        else quote_status
      end,
      updated_at = now()
  where id = any(p_order_ids)
    and guild_id = p_guild_id
    and not coalesce(paid, false);

  perform public.deepnight_consume_order_coupon(p_order_ids, v_customer_id);
  for v_order in
    select * from public.play_orders
    where id = any(p_order_ids) and guild_id = p_guild_id
    order by id
  loop
    if (p_delivery_type = 'order_dispatch' and v_order.status = 'pending')
      or (p_delivery_type = 'customer_confirmation'
        and v_order.status = 'waiting_confirm')
    then
      perform public.deepnight_enqueue_delivery_recovery(
        p_guild_id, p_delivery_type, v_order.id::text,
        jsonb_build_object('order_id', v_order.id, 'confirmed_by', p_confirmed_by)
      );
    end if;
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'order_financial_effects', v_order.id::text,
      jsonb_build_object(
        'order_id', v_order.id,
        'payment_method', coalesce(v_order.payment_method, '客服確認'),
        'amount', coalesce(v_order.final_price, v_order.price, 0)
      )
    );
  end loop;

  select jsonb_agg(to_jsonb(o) order by o.id) into v_orders
  from public.play_orders o
  where o.id = any(p_order_ids) and o.guild_id = p_guild_id;
  return jsonb_build_object('orders', coalesce(v_orders, '[]'::jsonb));
end;
$function$;

-- Capacity CAS and the work-panel recovery job commit together.
create or replace function public.deepnight_accept_play_order(
  p_order_id uuid, p_player_id text, p_guild_id text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_order public.play_orders%rowtype;
  v_player_ids text[] := '{}'::text[];
  v_need_count integer;
  v_is_full boolean;
  v_next_status text;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  if coalesce(p_player_id, '') = '' then raise exception '找不到接單陪陪'; end if;
  select * into v_order from public.play_orders
  where id = p_order_id and guild_id = p_guild_id for update;
  if not found then raise exception '找不到深夜訂單'; end if;
  if not coalesce(v_order.paid, false) then raise exception '訂單尚未付款，不能接單'; end if;
  if v_order.status is null or v_order.status not in ('pending', 'accepted')
    or coalesce(v_order.is_deleted, false)
  then raise exception '這張訂單目前不能接單'; end if;
  if not exists (
    select 1 from public.players player
    where player.discord_id = p_player_id
      and (
        player.guild_id is null
        or p_guild_id = any(
          regexp_split_to_array(coalesce(player.guild_id, ''), '\s*,\s*')
        )
      )
      and player.status = 'available'
      and coalesce(player.is_active, true)
      and coalesce(player.can_take_order, true)
  ) then
    raise exception '陪陪目前不是可接單狀態';
  end if;

  select coalesce(array_agg(btrim(part) order by ordinal), '{}'::text[])
  into v_player_ids
  from unnest(string_to_array(coalesce(v_order.assigned_player, ''), ','))
    with ordinality as existing(part, ordinal)
  where btrim(part) <> '';
  if p_player_id = any(v_player_ids) then raise exception '你已經接過這張訂單了'; end if;
  v_need_count := greatest(1, coalesce(v_order.player_count, 1));
  if cardinality(v_player_ids) >= v_need_count then raise exception '這張訂單名額已滿'; end if;

  v_player_ids := array_append(v_player_ids, p_player_id);
  v_is_full := cardinality(v_player_ids) >= v_need_count;
  v_next_status := case when v_is_full then 'accepted' else 'pending' end;
  update public.play_orders
  set assigned_player = array_to_string(v_player_ids, ','), status = v_next_status,
      accepted_at = case when v_is_full then coalesce(accepted_at, now()) else accepted_at end,
      updated_at = now()
  where id = p_order_id and guild_id = p_guild_id returning * into v_order;

  if v_is_full then
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'work_report_panel', p_order_id::text,
      jsonb_build_object('order_id', p_order_id)
    );
  end if;
  return jsonb_build_object('order', to_jsonb(v_order),
    'assigned_player_ids', to_jsonb(v_player_ids), 'is_full', v_is_full,
    'need_count', v_need_count);
end;
$function$;

-- Customer confirmation is another state boundary: status and the durable
-- staff-dispatch job must commit together or a process crash can orphan a paid
-- order between them.
create or replace function public.deepnight_confirm_order_and_enqueue(
  p_order_id uuid,
  p_customer_id text,
  p_guild_id text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare v_order public.play_orders%rowtype;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  select * into v_order from public.play_orders
  where id = p_order_id and guild_id = p_guild_id for update;
  if not found then raise exception '找不到深夜訂單'; end if;
  if v_order.customer_id is distinct from p_customer_id then
    raise exception '訂單付款人不一致';
