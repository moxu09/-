-- Financial side effects have separate durable checkpoints.  A retry may
-- therefore resume after VIP processing without writing the accounting row a
-- second time (and vice versa).  Attempt fencing prevents an expired worker
-- from checkpointing a newer worker's lease.
create or replace function public.deepnight_checkpoint_delivery_effect(
  p_job_id bigint,
  p_guild_id text,
  p_attempt integer,
  p_effect text
)
returns boolean
language plpgsql security definer set search_path = public
as $function$
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
