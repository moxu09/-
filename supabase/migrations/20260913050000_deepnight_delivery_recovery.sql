create or replace function public.deepnight_claim_delivery_recovery(
  p_job_id bigint,
  p_guild_id text,
  p_stale_seconds integer default 300
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_job public.bot_delivery_recovery_jobs%rowtype;
  v_attempt integer;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  select * into v_job
  from public.bot_delivery_recovery_jobs
  where id = p_job_id and organization_code = 'deepnight' and guild_id = p_guild_id
  for update;
  if not found then
    return jsonb_build_object('claimed', false, 'reason', 'not_found');
  end if;
  if v_job.status = 'completed' then
    return jsonb_build_object('claimed', false, 'reason', 'completed');
  end if;
  if v_job.status = 'processing' and v_job.claimed_at is not null
    and v_job.claimed_at > now() - make_interval(secs => greatest(30, p_stale_seconds))
  then
    return jsonb_build_object('claimed', false, 'reason', 'leased');
  end if;

  v_attempt := coalesce(v_job.attempts, 0) + 1;
  update public.bot_delivery_recovery_jobs
  set status = 'processing', attempts = v_attempt, claimed_at = now(),
      completed_at = null, last_error = null, updated_at = now()
  where id = v_job.id and organization_code = 'deepnight' and guild_id = p_guild_id;

  return jsonb_build_object(
    'claimed', true,
    'attempt', v_attempt,
    'job', to_jsonb(v_job) || jsonb_build_object('status', 'processing', 'attempts', v_attempt)
  );
end;
$function$;

