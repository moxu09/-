    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'tip_work_report_panel', v_order.id::text,
      jsonb_build_object('order_id', v_order.id)
    );
  end loop;

  v_result := jsonb_build_object(
    'already_processed', false, 'orders', v_orders, 'amount', v_total,
    'adjustment_id', v_adjustment_id, 'payment_method', p_payment_method,
