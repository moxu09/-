-- Two-row VALORANT payment remains all-or-nothing and each row queues its own
-- idempotent dispatch recovery before the transaction commits.
create or replace function public.deepnight_pay_service_group(
  p_group_id text, p_customer_id text, p_guild_id text, p_method text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_order public.play_orders%rowtype;
  v_order_ids uuid[] := '{}'::uuid[];
  v_order_id uuid;
  v_receipt jsonb;
  v_total numeric := 0;
  v_orders jsonb;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  if p_method not in ('wallet', 'monthly') then raise exception '不支援的付款方式'; end if;

  for v_order in
    select * from public.play_orders
    where order_group_id = p_group_id and guild_id = p_guild_id
    order by id for update
  loop
    if v_order.customer_id is distinct from p_customer_id
      or coalesce(v_order.paid, false) or coalesce(v_order.is_deleted, false)
      or v_order.status is null
      or v_order.status not in ('waiting_payment', 'quoted', 'waiting_confirm')
    then raise exception '訂單已付款或已結束，未重複扣款'; end if;
    v_order_ids := array_append(v_order_ids, v_order.id);
  end loop;
  if cardinality(v_order_ids) <> 2 then raise exception '分單資料不完整，未扣款'; end if;

  foreach v_order_id in array v_order_ids loop
    if p_method = 'wallet' then
      select to_jsonb(public.deepnight_pay_play_order_with_wallet(
        v_order_id, p_customer_id, p_guild_id)) into v_receipt;
    else
      select to_jsonb(public.deepnight_pay_play_order_with_monthly(
        v_order_id, p_customer_id, p_guild_id)) into v_receipt;
    end if;
    v_total := v_total + coalesce((v_receipt->>'amount')::numeric, 0);
  end loop;

  update public.play_orders set status = 'pending', quote_status = 'dispatched', updated_at = now()
  where id = any(v_order_ids) and guild_id = p_guild_id;
  foreach v_order_id in array v_order_ids loop
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'order_dispatch', v_order_id::text,
      jsonb_build_object('order_id', v_order_id, 'order_group_id', p_group_id)
    );
  end loop;
  select jsonb_agg(to_jsonb(o) order by o.id) into v_orders
  from public.play_orders o where o.id = any(v_order_ids) and o.guild_id = p_guild_id;
  return jsonb_build_object('amount', v_total, 'receipt', v_receipt,
    'orders', coalesce(v_orders, '[]'::jsonb));
end;
$function$;

