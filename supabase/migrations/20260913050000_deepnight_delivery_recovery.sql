-- Promote only the level fields while holding the latest user_vips row lock.
-- Node never writes a stale total snapshot back over a concurrent payment.
create or replace function public.deepnight_promote_vip_level(
  p_guild_id text, p_user_id text, p_level_key text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_vip public.user_vips%rowtype;
  v_level public.vip_levels%rowtype;
  v_previous_sort integer := 0;
  v_requested_sort integer := 0;
  v_actual_sort integer := 0;
  v_previous_level_key text;
  v_promoted boolean := false;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception 'VIP 等級更新 guild_id 不屬於深夜';
  end if;
  select * into v_level from public.vip_levels
  where guild_id = p_guild_id and level_key = p_level_key;
  if not found then raise exception '找不到 VIP 等級設定'; end if;
  v_requested_sort := coalesce(v_level.sort_order, 0);

  select * into v_vip from public.user_vips
  where guild_id = p_guild_id and user_id = p_user_id
  for update;
  if not found then raise exception '找不到 VIP 累積資料'; end if;
  v_previous_level_key := v_vip.level_key;
  select coalesce(sort_order, 0) into v_previous_sort
  from public.vip_levels
  where guild_id = p_guild_id and level_key = v_vip.level_key;
  if not found then v_previous_sort := 0; end if;

  if v_requested_sort > v_previous_sort then
    update public.user_vips
    set level_key = v_level.level_key,
        level_name = v_level.level_name,
        updated_at = now()
    where id = v_vip.id
    returning * into v_vip;
    v_actual_sort := v_requested_sort;
    v_promoted := true;
  else
    v_actual_sort := v_previous_sort;
  end if;
  return jsonb_build_object(
    'promoted', v_promoted,
    'previous_level_key', v_previous_level_key,
    'previous_sort_order', v_previous_sort,
    'level_key', v_vip.level_key,
    'level_name', v_vip.level_name,
    'sort_order', v_actual_sort,
    'vip', to_jsonb(v_vip)
  );
end;
$function$;

-- Monetary/coupon/log rewards are committed exactly once per user+level.
-- Only the idempotent Discord role/notification delivery remains asynchronous.
create or replace function public.deepnight_apply_vip_level_reward(
  p_guild_id text,
  p_user_id text,
  p_level_key text,
  p_old_level_key text,
  p_trigger_type text,
  p_trigger_amount numeric,
  p_reward_coupons jsonb
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_operation public.bot_vip_reward_operations%rowtype;
  v_level public.vip_levels%rowtype;
  v_coupon jsonb;
  v_coupon_name text;
  v_coupon_count integer;
  v_final_balance integer;
  v_guild text := trim(coalesce(p_guild_id, ''));
  v_user text := trim(coalesce(p_user_id, ''));
  v_level_key text := trim(coalesce(p_level_key, ''));
begin
  if v_guild <> '1501098191813214312' then
    raise exception 'VIP 升等獎勵 guild_id 不屬於深夜';
  end if;
  if v_user = '' or v_level_key = '' then raise exception 'VIP 升等獎勵資料不完整'; end if;
  if p_trigger_type not in ('topup', 'spend') then raise exception 'VIP 升等獎勵觸發類型錯誤'; end if;
  if jsonb_typeof(coalesce(p_reward_coupons, '[]'::jsonb)) <> 'array' then
    raise exception 'VIP 優惠券獎勵格式錯誤';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(
    'deepnight-vip-reward:' || v_guild || ':' || v_user || ':' || v_level_key,
    0
  ));

  select * into v_operation from public.bot_vip_reward_operations
  where organization_code = 'deepnight' and guild_id = v_guild
    and user_id = v_user and level_key = v_level_key
  for update;
  if found then
    return to_jsonb(v_operation) || jsonb_build_object('already_applied', true);
  end if;

  select * into v_level from public.vip_levels
  where guild_id = v_guild and level_key = v_level_key
  for update;
  if not found then raise exception '找不到 VIP 等級獎勵設定'; end if;

  insert into public.users(user_id, coins) values (v_user, 0)
  on conflict (user_id) do nothing;
  select coalesce(coins, 0) into v_final_balance
  from public.users where user_id = v_user for update;
  if coalesce(v_level.reward_asd, 0) > 0 then
    update public.users
    set coins = coalesce(coins, 0) + v_level.reward_asd
    where user_id = v_user returning coins into v_final_balance;
    insert into public.wallet_logs(user_id, type, amount, balance, note)
    values (
      v_user, 'VIP升級獎勵', v_level.reward_asd, v_final_balance,
      '升級 ' || v_level.level_name || '｜獲得 ' || v_level.reward_asd::text || ' ASD'
    );
  end if;

  for v_coupon in
    select value from jsonb_array_elements(coalesce(p_reward_coupons, '[]'::jsonb))
  loop
    v_coupon_name := trim(coalesce(v_coupon->>'name', ''));
    v_coupon_count := coalesce((v_coupon->>'count')::integer, 0);
    if v_coupon_name = '' or v_coupon_count <= 0 or v_coupon_count > 100 then
      raise exception 'VIP 優惠券獎勵內容錯誤';
    end if;
    insert into public.user_items(
      user_id, item_name, rarity, description, item_type, guild_id
    )
    select v_user, v_coupon_name, 'VIP',
      v_level.level_name || ' 升級獎勵', 'coupon', v_guild
    from generate_series(1, v_coupon_count);
  end loop;

  insert into public.vip_upgrade_logs(
    guild_id, user_id, old_level_key, new_level_key, trigger_type,
    trigger_amount, reward_asd, reward_coupon, reward_note
  ) values (
    v_guild, v_user, p_old_level_key, v_level_key, p_trigger_type,
    coalesce(p_trigger_amount, 0)::integer, coalesce(v_level.reward_asd, 0),
    v_level.reward_coupon, v_level.reward_note
  );

  insert into public.bot_vip_reward_operations(
    organization_code, guild_id, user_id, level_key, old_level_key,
    trigger_type, trigger_amount, reward_asd, reward_coupons, reward_note,
    role_id, level_name, final_balance, delivery_status
  ) values (
    'deepnight', v_guild, v_user, v_level_key, p_old_level_key,
    p_trigger_type, coalesce(p_trigger_amount, 0)::integer,
    coalesce(v_level.reward_asd, 0), coalesce(p_reward_coupons, '[]'::jsonb),
    v_level.reward_note, v_level.role_id, v_level.level_name,
    v_final_balance, 'pending'
  ) returning * into v_operation;
  return to_jsonb(v_operation) || jsonb_build_object('already_applied', false);
end;
$function$;

create or replace function public.deepnight_claim_vip_reward_delivery(
  p_guild_id text, p_user_id text, p_level_key text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare v_operation public.bot_vip_reward_operations%rowtype;
begin
  if p_guild_id is distinct from '1501098191813214312' then raise exception 'VIP 獎勵派送 guild 不屬於深夜'; end if;
  select * into v_operation from public.bot_vip_reward_operations
  where organization_code = 'deepnight' and guild_id = p_guild_id
    and user_id = p_user_id and level_key = p_level_key for update;
  if not found then raise exception '找不到 VIP 獎勵派送資料'; end if;
  if v_operation.delivery_status = 'completed' then
    return jsonb_build_object('claimed', false, 'state', 'completed', 'operation', to_jsonb(v_operation));
  end if;
  if v_operation.delivery_status = 'processing'
    and v_operation.delivery_claimed_at > now() - interval '2 minutes'
  then
    return jsonb_build_object('claimed', false, 'state', 'processing', 'operation', to_jsonb(v_operation));
  end if;
  update public.bot_vip_reward_operations
  set delivery_status = 'processing', delivery_attempts = delivery_attempts + 1,
      delivery_claimed_at = now(), delivery_last_error = null, updated_at = now()
  where organization_code = 'deepnight' and guild_id = p_guild_id
    and user_id = p_user_id and level_key = p_level_key
  returning * into v_operation;
  return jsonb_build_object('claimed', true, 'state', 'processing',
    'attempt', v_operation.delivery_attempts, 'operation', to_jsonb(v_operation));
end;
$function$;

