    case when v_matched then floor(v_amount * 0.03) else 0 end,
    greatest(0, 30000 - v_month_cashback)
  );

  update public.member_monthly_accounts
  set used_amount = coalesce(used_amount, 0) + v_amount, updated_at = now()
  where user_id = p_customer_id returning * into v_account;
  insert into public.member_monthly_transactions(
    user_id, source_type, source_id, item_name, benefit_type,
    amount, cashback, billing_month, status
  ) values (
    p_customer_id, 'order_extension', p_extension_id::text,
    v_item_name, v_benefit_type, v_amount, v_cashback, v_billing_month, 'unbilled'
  );
  update public.order_extensions
  set payment_method = '月結', paid = true, status = 'paid',
      paid_at = coalesce(paid_at, now()), updated_at = now()
  where id = p_extension_id and guild_id = p_guild_id
