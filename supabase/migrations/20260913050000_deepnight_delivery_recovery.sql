-- Marking a JKOPay order paid validates the frozen gateway payment and writes
-- the paid state, coupon consumption and all recovery jobs in one transaction.
create or replace function public.deepnight_mark_jkopay_orders_paid(
  p_platform_order_id text,
  p_guild_id text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_payment public.jkopay_service_payments%rowtype;
  v_order public.play_orders%rowtype;
  v_order_ids uuid[] := '{}'::uuid[];
  v_count integer := 0;
  v_total numeric := 0;
  v_service_flow boolean := false;
  v_orders jsonb;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  select * into v_payment from public.jkopay_service_payments
  where organization_code = 'deepnight'
    and platform_order_id = p_platform_order_id
    and payment_kind = 'order'
  for update;
  if not found or v_payment.status <> 'paid' then
    raise exception '找不到已付款的深夜街口訂單';
  end if;
  select coalesce(array_agg(value::uuid), '{}'::uuid[])
  into v_order_ids
  from jsonb_array_elements_text(
    case when jsonb_typeof(v_payment.metadata->'orderIds') = 'array'
      then v_payment.metadata->'orderIds'
      else jsonb_build_array(v_payment.entity_key)
    end
  );
  if coalesce(cardinality(v_order_ids), 0) = 0 then
    raise exception '街口付款沒有對應訂單';
  end if;
  v_service_flow := coalesce(v_payment.metadata->>'flow', '') = 'service';

  for v_order in
    select * from public.play_orders
    where id = any(v_order_ids) and guild_id = p_guild_id
    order by id for update
  loop
    v_count := v_count + 1;
    if v_order.customer_id is distinct from v_payment.user_id
      or coalesce(v_order.is_deleted, false)
      or coalesce(v_order.status, '') in ('cancelled', 'refunded', 'completed')
    then raise exception '街口付款與深夜訂單狀態或付款人不一致'; end if;
    if not coalesce(v_order.paid, false)
      and v_order.status not in ('waiting_payment', 'quoted', 'waiting_confirm')
    then raise exception '深夜訂單目前不可付款'; end if;
    v_total := v_total + coalesce(v_order.final_price, v_order.price, 0);
  end loop;
  if v_count <> cardinality(v_order_ids) or v_total <> v_payment.amount then
    raise exception '街口付款對應訂單不完整或金額不一致';
  end if;
  if v_payment.entity_key like 'group-%' then
    if nullif(v_payment.metadata->>'orderGroupId', '') is null
      or v_payment.entity_key <> 'group-' || (v_payment.metadata->>'orderGroupId')
      or exists (
        select 1 from public.play_orders source_order
        where source_order.id = any(v_order_ids)
          and source_order.guild_id = p_guild_id
          and source_order.order_group_id is distinct from
            (v_payment.metadata->>'orderGroupId')
      )
    then raise exception '街口付款與深夜訂單群組不一致'; end if;
  elsif cardinality(v_order_ids) <> 1
    or v_order_ids[1]::text is distinct from v_payment.entity_key
  then raise exception '街口付款與深夜訂單編號不一致'; end if;

  update public.play_orders
  set payment_method = '街口支付', paid = true,
      paid_at = coalesce(paid_at, v_payment.paid_at, now()),
      status = case when v_service_flow then 'pending' else 'waiting_confirm' end,
      quote_status = case when v_service_flow then 'dispatched' else quote_status end,
      updated_at = now()
  where id = any(v_order_ids) and guild_id = p_guild_id
    and not coalesce(paid, false);
  perform public.deepnight_consume_order_coupon(v_order_ids, v_payment.user_id);

  for v_order in
    select * from public.play_orders
    where id = any(v_order_ids) and guild_id = p_guild_id order by id
  loop
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'order_financial_effects', v_order.id::text,
      jsonb_build_object('order_id', v_order.id, 'payment_method', '街口支付',
        'amount', coalesce(v_order.final_price, v_order.price, 0),
        'platform_order_id', p_platform_order_id)
    );
    if v_service_flow and v_order.status = 'pending' then
      perform public.deepnight_enqueue_delivery_recovery(
        p_guild_id, 'order_dispatch', v_order.id::text,
        jsonb_build_object('order_id', v_order.id)
      );
    elsif not v_service_flow and v_order.status = 'waiting_confirm' then
      perform public.deepnight_enqueue_delivery_recovery(
        p_guild_id, 'customer_confirmation', v_order.id::text,
        jsonb_build_object('order_id', v_order.id)
      );
    end if;
  end loop;
  select jsonb_agg(to_jsonb(source_order) order by source_order.id)
  into v_orders from public.play_orders source_order
  where source_order.id = any(v_order_ids) and source_order.guild_id = p_guild_id;
  return jsonb_build_object('orders', coalesce(v_orders, '[]'::jsonb),
    'amount', v_total, 'service_flow', v_service_flow);
end;
$function$;

