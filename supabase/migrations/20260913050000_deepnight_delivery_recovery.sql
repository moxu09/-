-- Increment DeepNight's VIP cumulative spend exactly once per paid order.  The
-- idempotency operation and user_vips update are in the same DB transaction,
-- so a process crash can neither lose the increment nor apply it twice.
create or replace function public.deepnight_apply_order_vip_spend_once(
  p_order_id uuid,
  p_guild_id text,
  p_frozen_amount numeric default null
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_order public.play_orders%rowtype;
  v_operation_key text := 'play-order:' || p_order_id::text || ':vip-spend';
  v_amount numeric;
  v_inserted integer := 0;
  v_total numeric := 0;
  v_operation_exists boolean := false;
  v_legacy_already_counted boolean := false;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  select * into v_order from public.play_orders
  where id = p_order_id and guild_id = p_guild_id
  for update;
  if not found then raise exception '找不到深夜訂單'; end if;
  if not coalesce(v_order.paid, false) then
    raise exception '訂單尚未付款，不可計入累積消費';
  end if;
  if coalesce(v_order.is_deleted, false)
    or v_order.status in ('cancelled', 'refunded')
  then
    raise exception '訂單已取消或退款，不可計入累積消費';
  end if;
  if coalesce(v_order.customer_id, '') = '' then
    raise exception '訂單缺少 customer_id';
  end if;
  v_amount := coalesce(
    nullif(p_frozen_amount, 0),
    v_order.final_price,
    v_order.price,
    0
  );
  if v_amount <= 0 then raise exception '訂單金額錯誤'; end if;

  select exists (
    select 1 from public.bot_financial_operations
    where organization_code = 'deepnight'
      and operation_key = v_operation_key
      and status = 'completed'
  ) into v_operation_exists;
  if v_operation_exists then
    select coalesce((result->>'legacy_already_counted')::boolean, false)
      into v_legacy_already_counted
    from public.bot_financial_operations
    where organization_code = 'deepnight'
      and operation_key = v_operation_key
      and status = 'completed';
  end if;

  -- Rows counted before this migration have no operation key.  Record a
  -- legacy marker but never add their amount again.
  if coalesce(v_order.vip_spent_counted, false) and not v_operation_exists then
    v_legacy_already_counted := true;
    insert into public.bot_financial_operations (
      organization_code, operation_key, operation_type,
      entity_id, actor_id, amount, status, result
    ) values (
      'deepnight', v_operation_key, 'order_vip_spend_legacy',
      p_order_id::text, v_order.customer_id, v_amount, 'completed',
      jsonb_build_object(
        'order_id', p_order_id,
        'guild_id', p_guild_id,
        'legacy_already_counted', true
      )
    )
    on conflict (organization_code, operation_key) do nothing;
    v_operation_exists := true;
  end if;

  if not v_operation_exists then
    insert into public.bot_financial_operations (
      organization_code, operation_key, operation_type,
      entity_id, actor_id, amount, status, result
    ) values (
      'deepnight', v_operation_key, 'order_vip_spend',
      p_order_id::text, v_order.customer_id, v_amount, 'completed',
      jsonb_build_object('order_id', p_order_id, 'guild_id', p_guild_id)
    )
    on conflict (organization_code, operation_key) do nothing;
    get diagnostics v_inserted = row_count;
  end if;

  if v_inserted = 1 then
    insert into public.user_vips (
      guild_id, user_id, level_key, level_name,
      total_spent, total_topup, highest_single_topup, updated_at
    ) values (
      p_guild_id, v_order.customer_id, null, null,
      v_amount, 0, 0, now()
    )
    on conflict (guild_id, user_id) do update
    set total_spent = coalesce(public.user_vips.total_spent, 0) + excluded.total_spent,
        updated_at = now();
  end if;

  select coalesce(total_spent, 0) into v_total
  from public.user_vips
  where guild_id = p_guild_id and user_id = v_order.customer_id;
  if not found then raise exception '找不到 VIP 累積資料'; end if;

  update public.play_orders
  set vip_spent_counted = true,
      vip_spent_counted_at = coalesce(vip_spent_counted_at, now()),
      updated_at = now()
  where id = p_order_id and guild_id = p_guild_id;

  update public.bot_financial_operations
  set result = result || jsonb_build_object(
        'total_spent', v_total,
        'legacy_already_counted', v_legacy_already_counted
      ),
      updated_at = now()
  where organization_code = 'deepnight'
    and operation_key = v_operation_key;

  return jsonb_build_object(
    'applied', v_inserted = 1,
    'already_processed', v_inserted = 0,
    'amount', v_amount,
    'total_spent', v_total,
    'customer_id', v_order.customer_id,
    'legacy_already_counted', v_legacy_already_counted
  );
end;
