-- Serialize all DeepNight salary-deduction payments for one employee on the
-- active players row and re-evaluate the advance cap inside the transaction.
create or replace function public.deepnight_assert_salary_deduction_available(
  p_customer_id text,
  p_guild_id text,
  p_amount numeric
)
returns text
language plpgsql security definer set search_path = public
as $function$
declare
  v_staff public.players%rowtype;
  v_wallet_start timestamptz := '2026-07-17 00:00:00+08'::timestamptz;
  v_wallet numeric := 0;
  v_withdrawals numeric := 0;
  v_pending_salary numeric := 0;
  v_adjustments numeric := 0;
  v_available numeric := 0;
  v_projected_advance numeric := 0;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  if coalesce(p_customer_id, '') = '' or coalesce(p_amount, 0) <= 0 then
    raise exception '扣薪付款參數錯誤';
  end if;
  select * into v_staff from public.players
  where (
      guild_id is null
      or p_guild_id = any(regexp_split_to_array(coalesce(guild_id, ''), '\s*,\s*'))
    )
    and discord_id = p_customer_id and is_active = true
  for update;
  if not found then raise exception '扣薪付款僅限深夜不關燈在職員工使用'; end if;

  select coalesce(sum(amount), 0) into v_wallet
  from public.salary_wallet_entries
  where app_key = 'deepnight' and discord_id = p_customer_id;
  select coalesce(sum(amount), 0) into v_withdrawals
  from public.salary_withdraw_requests
  where app_key = 'deepnight' and discord_id = p_customer_id
    and status in ('pending', 'approved');
  select coalesce(sum(coalesce(staff_salary, 0) + coalesce(bonus_amount, 0)), 0)
  into v_pending_salary
  from public.play_orders
  where discord_id = p_customer_id
    and guild_id = '1501098191813214312'
    and order_finished_at >= v_wallet_start
    and wallet_settled_at is null
    and not coalesce(is_deleted, false)
    and coalesce(status, '') <> '已入帳';
  select coalesce(sum(amount), 0) into v_adjustments
  from public.players_bonus
  where discord_id = p_customer_id
    and created_at >= v_wallet_start
    and wallet_settled_at is null;

  v_available := v_wallet - v_withdrawals + v_pending_salary + v_adjustments;
  v_projected_advance := greatest(0, -(v_available - p_amount));
  if v_projected_advance > 1000 then
    raise exception '本筆扣薪後預支額度 % 超過上限 NT$1,000', v_projected_advance;
  end if;
  return coalesce(
    v_staff.display_name,
    v_staff.real_name,
    v_staff.discord_name,
    v_staff.discord_id,
    '員工'
  );
end;
$function$;

-- Employee order payment: deduction adjustment, paid rows, coupon consume and
-- all downstream recovery jobs commit as one transaction.
create or replace function public.deepnight_pay_orders_with_salary(
  p_order_ids uuid[],
  p_customer_id text,
  p_guild_id text,
  p_final_status text,
  p_quote_status text,
  p_confirmed_by text
)
returns jsonb
language plpgsql security definer set search_path = public
as $function$
declare
  v_order public.play_orders%rowtype;
  v_order_id uuid;
  v_ids uuid[] := '{}'::uuid[];
  v_total numeric := 0;
  v_count integer := 0;
  v_staff_name text;
  v_operation_key text;
  v_existing jsonb;
  v_adjustment_id uuid;
  v_orders jsonb;
  v_delivery_type text;
begin
  if p_guild_id is distinct from '1501098191813214312' then
    raise exception '不是深夜不關燈伺服器';
  end if;
  if coalesce(cardinality(p_order_ids), 0) = 0
    or p_final_status not in ('pending', 'waiting_confirm')
  then raise exception '扣薪訂單參數錯誤'; end if;

  for v_order in
    select * from public.play_orders
    where id = any(p_order_ids) and guild_id = p_guild_id
    order by id for update
  loop
    v_count := v_count + 1;
    v_ids := array_append(v_ids, v_order.id);
    if v_order.customer_id is distinct from p_customer_id then
      raise exception '扣薪訂單付款人不一致';
    end if;
    v_total := v_total + coalesce(v_order.final_price, v_order.price, 0);
  end loop;
  if v_count <> cardinality(p_order_ids) or v_total <= 0 then
    raise exception '扣薪訂單不完整或金額錯誤';
  end if;

  v_operation_key := 'salary-orders:' || md5(array_to_string(v_ids, ','));
  select result into v_existing from public.bot_financial_operations
  where organization_code = 'deepnight' and operation_key = v_operation_key
    and status = 'completed';
  if found then return v_existing || jsonb_build_object('already_processed', true); end if;

  if exists (
    select 1 from public.play_orders
    where id = any(v_ids) and guild_id = p_guild_id
      and (coalesce(paid, false) or coalesce(is_deleted, false)
        or status not in ('waiting_payment', 'quoted', 'waiting_confirm'))
  ) then raise exception '訂單已付款、取消或結束，未建立扣薪'; end if;

  v_staff_name := public.deepnight_assert_salary_deduction_available(
    p_customer_id, p_guild_id, v_total
  );
  insert into public.players_bonus(
    discord_id, staff_name, bonus_type, description, amount, created_at
  ) values (
    p_customer_id, v_staff_name, '薪水扣除', '使用薪水點單', -v_total, now()
  ) returning id into v_adjustment_id;

  update public.play_orders
  set payment_method = '扣薪', paid = true,
      paid_at = coalesce(paid_at, now()), status = p_final_status,
      quote_status = coalesce(p_quote_status, quote_status), updated_at = now()
  where id = any(v_ids) and guild_id = p_guild_id;
  perform public.deepnight_consume_order_coupon(v_ids, p_customer_id);

  v_delivery_type := case
    when p_final_status = 'pending' then 'order_dispatch'
    else 'customer_confirmation'
  end;
  foreach v_order_id in array v_ids loop
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, 'order_financial_effects', v_order_id::text,
      jsonb_build_object(
        'order_id', v_order_id,
        'payment_method', '扣薪',
        'amount', (
          select coalesce(frozen_order.final_price, frozen_order.price, 0)
          from public.play_orders frozen_order
          where frozen_order.id = v_order_id and frozen_order.guild_id = p_guild_id
        )
      )
    );
    perform public.deepnight_enqueue_delivery_recovery(
      p_guild_id, v_delivery_type, v_order_id::text,
      jsonb_build_object('order_id', v_order_id)
    );
  end loop;

  select jsonb_agg(to_jsonb(o) order by o.id) into v_orders
  from public.play_orders o
  where o.id = any(v_ids) and o.guild_id = p_guild_id;
  v_existing := jsonb_build_object(
    'already_processed', false,
    'amount', v_total,
    'adjustment_id', v_adjustment_id,
    'confirmed_by', p_confirmed_by,
    'orders', coalesce(v_orders, '[]'::jsonb)
  );
  insert into public.bot_financial_operations(
    organization_code, operation_key, operation_type, entity_id,
    actor_id, amount, status, result
  ) values (
    'deepnight', v_operation_key, 'salary_order_payment',
    array_to_string(v_ids, ','), p_confirmed_by, v_total, 'completed', v_existing
  );
  return v_existing;
end;
$function$;

